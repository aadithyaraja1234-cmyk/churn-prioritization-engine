import json
from pathlib import Path

import pandas as pd

from src.models.recommend import apply_priority_prefix, determine_recommendation, recommend_action_for_customer

MEDIAN_CHARGES = 70.0

# Meridian Wireless: a real self-registered tenant. Since Stage 2b
# (src/models/tenant_training.py's _run_optional_modules()) segment_model.pkl/
# anomaly_model.pkl are now trained unconditionally for every tenant - only
# CLV genuinely stays missing here (no clv_column was mapped for Meridian's
# real upload). Real artifacts, not mocks, so this test exercises the
# exact same code path production hits for a CLV-only-missing tenant.
MERIDIAN_MODEL_DIR = "models/meridian-wireless"
MERIDIAN_DATA_PATH = "data/tenant_uploads/meridian-wireless.csv"
MERIDIAN_TEST_CUSTOMER_ID = "MW-49541-DFWC"


def _first_real_telco_test_split_customer_id() -> str:
    """Resolves a real customerID that's actually in models/v1's CURRENT
    test split, rather than hardcoding one - split_indices.json is
    regenerated by every real retrain (e.g. src/models/train.py's
    hyperparameter tuning), so a hardcoded ID silently goes stale the
    first time anyone retrains Telco with a different split-affecting
    change, exactly as one did here (models/v1/split_indices.json had not
    actually been regenerated in a long time before this session, and the
    previously-hardcoded ID's split membership was stale)."""
    split_info = json.loads((Path("models") / "v1" / "split_indices.json").read_text(encoding="utf-8"))
    df = pd.read_csv("data/raw/telco.csv")
    return df.loc[split_info["test_idx"][0], "customerID"]


def test_rule_a_contract_driver_high_charges_recommends_discount():
    result = determine_recommendation(
        top_feature_names=["Contract", "tenure"],
        monthly_charges=100.0,  # above median
        monthly_charges_median=MEDIAN_CHARGES,
        churn_probability=0.9,
        is_anomaly=False,
        is_highest_risk_segment=False,
    )
    assert result["action"] == "Offer a discount or loyalty pricing to reduce price sensitivity"
    assert "Contract" in result["triggered_by"]


