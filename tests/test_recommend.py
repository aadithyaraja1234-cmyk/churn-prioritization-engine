    test_customer_id = _first_real_telco_test_split_customer_id()
    result = recommend_action_for_customer(
        test_customer_id,
        model_dir="models/v1",
        data_path="data/raw/telco.csv",
        clv_data_path="data/raw/telco_enriched.csv",
    )
    assert result["based_on"] == ["churn_probability", "clv", "segment", "anomaly"]


